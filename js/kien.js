    const initTypingEffect = () => {
        const typingEl = document.getElementById('typingText');
        if (!typingEl) return;

        let phrases = (window.I18N && window.I18N[currentLang]) 
            ? window.I18N[currentLang].typingPhrases 
            : [
                'Sinh viên Công nghệ Thông tin',
                'Nhiếp ảnh gia & Sáng tạo',
                'Sinh viên K24 · UTH'
            ];

        let phraseIndex = 0;
        let charIndex = 0;
        let isDeleting = false;
        let typingSpeed = 90;
        let typeTimer = null;

        const type = () => {
            const currentPhrase = phrases[phraseIndex] || '';

            if (isDeleting) {
                typingEl.textContent = currentPhrase.substring(0, Math.max(0, charIndex - 1));
                charIndex--;
                typingSpeed = 40;
            } else {
                typingEl.textContent = currentPhrase.substring(0, charIndex + 1);
                charIndex++;
                typingSpeed = 90;
            }

            if (!isDeleting && charIndex === currentPhrase.length) {
                isDeleting = true;
                typingSpeed = 1600; // Pause at end of phrase
            } else if (isDeleting && charIndex <= 0) {
                isDeleting = false;
                phraseIndex = (phraseIndex + 1) % phrases.length;
                typingSpeed = 400; // Pause before new phrase
            }

            typeTimer = setTimeout(type, typingSpeed);
        };

        type();

        updateTypingPhrases = (newPhrases) => {
            if (!newPhrases || !newPhrases.length) return;
            phrases = newPhrases;
            phraseIndex = 0;
            charIndex = 0;
            isDeleting = false;
            if (typeTimer) clearTimeout(typeTimer);
            type();
        };
    };

    /* ==========================================================================
       FEATURE 6: AMBIENT PARTICLE CANVAS
       ========================================================================== */
    const initParticleCanvas = () => {
        const canvas = document.getElementById('particleCanvas');
        if (!canvas) return;

        const ctx = canvas.getContext('2d');
        let width = (canvas.width = window.innerWidth);
        let height = (canvas.height = window.innerHeight);

        const PARTICLE_COUNT = Math.min(50, Math.floor(width / 30));
        const particles = [];

        class Particle {
            constructor() {
                this.reset();
            }

            reset() {
                this.x = Math.random() * width;
                this.y = Math.random() * height;
                this.radius = Math.random() * 1.5 + 0.5;
                this.vx = (Math.random() - 0.5) * 0.35;
                this.vy = (Math.random() - 0.5) * 0.35;
                this.alpha = Math.random() * 0.6 + 0.2;
                this.color = Math.random() > 0.5 ? '59, 130, 246' : '139, 92, 246';
            }

            update() {
                this.x += this.vx;
                this.y += this.vy;

                if (this.x < 0 || this.x > width) this.vx *= -1;
                if (this.y < 0 || this.y > height) this.vy *= -1;
            }

            draw() {
                ctx.beginPath();
                ctx.arc(this.x, this.y, this.radius, 0, Math.PI * 2);
                ctx.fillStyle = `rgba(${this.color}, ${this.alpha})`;
                ctx.fill();
            }
        }

        for (let i = 0; i < PARTICLE_COUNT; i++) {
            particles.push(new Particle());
        }

        let animationFrameId;

        const animate = () => {
            ctx.clearRect(0, 0, width, height);

            particles.forEach((p) => {
                p.update();
                p.draw();
            });

            animationFrameId = requestAnimationFrame(animate);
        };

        animate();

        window.addEventListener('resize', () => {
            width = canvas.width = window.innerWidth;
            height = canvas.height = window.innerHeight;
        });
    };

