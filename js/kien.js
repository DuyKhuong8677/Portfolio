    const initContactForm = () => {
        const form = document.getElementById('contactForm');
        if (!form) return;

        const nameInput = document.getElementById('formName');
        const emailInput = document.getElementById('formEmail');
        const messageInput = document.getElementById('formMessage');
        const nameError = document.getElementById('nameError');
        const emailError = document.getElementById('emailError');
        const messageError = document.getElementById('messageError');
        const submitBtn = document.getElementById('formSubmit');
        const formSuccess = document.getElementById('formSuccess');

        const EMAIL_REGEX = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;

        const validateName = () => {
            const val = nameInput.value.trim();
            const dict = (window.I18N && window.I18N[currentLang]) || {};
            if (!val) {
                nameError.textContent = dict.errNameReq || 'Vui lòng nhập họ và tên của bạn.';
                nameInput.style.borderColor = '#ef4444';
                return false;
            }
            nameError.textContent = '';
            nameInput.style.borderColor = '';
            return true;
        };

        const validateEmail = () => {
            const val = emailInput.value.trim();
            const dict = (window.I18N && window.I18N[currentLang]) || {};
            if (!val) {
                emailError.textContent = dict.errEmailReq || 'Vui lòng cung cấp địa chỉ email liên hệ.';
                emailInput.style.borderColor = '#ef4444';
                return false;
            }
            if (!EMAIL_REGEX.test(val)) {
                emailError.textContent = dict.errEmailInvalid || 'Định dạng email không hợp lệ (ví dụ: name@gmail.com).';
                emailInput.style.borderColor = '#ef4444';
                return false;
            }
            emailError.textContent = '';
            emailInput.style.borderColor = '';
            return true;
        };

        const validateMessage = () => {
            const val = messageInput.value.trim();
            const dict = (window.I18N && window.I18N[currentLang]) || {};
            if (!val) {
                messageError.textContent = dict.errMsgReq || 'Vui lòng nhập nội dung tin nhắn.';
                messageInput.style.borderColor = '#ef4444';
                return false;
            }
            if (val.length < 10) {
                messageError.textContent = dict.errMsgShort || 'Nội dung tin nhắn tối thiểu 10 ký tự.';
                messageInput.style.borderColor = '#ef4444';
                return false;
            }
            messageError.textContent = '';
            messageInput.style.borderColor = '';
            return true;
        };

        nameInput.addEventListener('input', validateName);
        emailInput.addEventListener('input', validateEmail);
        messageInput.addEventListener('input', validateMessage);

        form.addEventListener('submit', (e) => {
            e.preventDefault();

            const isNameValid = validateName();
            const isEmailValid = validateEmail();
            const isMsgValid = validateMessage();

            if (!isNameValid || !isEmailValid || !isMsgValid) {
                showToast('Vui lòng kiểm tra lại thông tin biểu mẫu', 'fa-exclamation-circle');
                return;
            }

            // Simulate loading state
            submitBtn.disabled = true;
            submitBtn.innerHTML = `<i class="fas fa-spinner fa-spin"></i><span>Đang gửi tin nhắn...</span>`;

            setTimeout(() => {
                formSuccess.classList.add('show');
                showToast('Tin nhắn gửi thành công!', 'fa-paper-plane');
                form.reset();

                submitBtn.disabled = false;
                submitBtn.innerHTML = `<i class="fas fa-paper-plane"></i><span>Gửi tin nhắn đi</span>`;

                setTimeout(() => {
                    formSuccess.classList.remove('show');
                }, 5000);
            }, 800);
        });
    };

